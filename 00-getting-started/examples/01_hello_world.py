"""Print a greeting to the screen: the traditional first program.

Run: python 01_hello_world.py
"""

# print() writes whatever is inside the brackets to the screen.
# Text must be wrapped in quotes so Python knows it is text, not a name.
print("Hello, World!")

# Each print() call starts on a new line.
print("I am learning Python.")

# Double quotes and single quotes both work for text.
print('Single quotes work too.')

# A blank print() prints an empty line, which is handy for spacing output.
print()

# Numbers do not need quotes. Python calculates the value, then prints it.
print(7 * 6)
